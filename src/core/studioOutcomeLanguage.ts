/** Offline fallback follows the current Persian conversation; model-authored text is preserved. */
export function localizeStudioOutcome(session: StudioAgentPersistedSession, text: string): string {
  const requests = session.events.filter((event) => event.type === 'request.started').slice(-8);
  const languageContext =
    requests.map((event) => String(event.data.request ?? '')).join('\n') +
    '\n' +
    (session.taskLedger?.objective ?? '');
  if (!/[\u067e\u0686\u0698\u06af\u06a9\u06cc]/.test(languageContext)) {
    return text;
  }
  return text
    .split('\n')
    .map((line) => {
      for (const [source, translated] of Object.entries(persian)) {
        if (line === source || (source.endsWith(' ') && line.startsWith(source))) {
          return translated + line.slice(source.length);
        }
      }
      return line;
    })
    .join('\n');
}
